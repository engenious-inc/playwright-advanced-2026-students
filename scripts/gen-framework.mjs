#!/usr/bin/env node
// Deterministic manifest -> Playwright framework generator (M08 lecture 8.F).
//
// Reads a declarative manifest (the single source of truth) and compiles it into a
// self-contained POM framework: a page object per `pages[]`, a typed fixtures file, a
// seed spec, and one journey spec per `journeys[]` — organized by journey and carrying
// specSource / step / evidence traceability comments back to the manifest.
//
// The output is generator-owned: `npm run gen:framework` rewrites it wholesale, and
// `--check` regenerates in memory and fails on any drift. No generated file is hand-edited.
// Output is run through the repo's Prettier config so it always matches `format:check`.
//
// Usage:
//   node scripts/gen-framework.mjs [manifest.json]           # write output
//   node scripts/gen-framework.mjs [manifest.json] --check   # verify no drift (CI gate)

import { readFileSync, readdirSync, existsSync, rmSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const check = argv.includes('--check');
const manifestArg = argv.find((a) => !a.startsWith('--')) ?? 'specs/m08-tubi-livetv.manifest.json';
const MANIFEST_PATH = resolve(REPO_ROOT, manifestArg);
const MANIFEST_REL = relative(REPO_ROOT, MANIFEST_PATH);

const banner = () =>
  `// GENERATED by scripts/gen-framework.mjs from ${MANIFEST_REL}.\n` +
  '// Do NOT hand-edit — change the manifest and run `npm run gen:framework`.\n\n';

// TubiLiveTvPage -> tubiLiveTv (fixture + local var name).
const fixtureName = (pageName) => {
  const base = pageName.replace(/Page$/, '');
  return base.charAt(0).toLowerCase() + base.slice(1);
};

const sq = (s) => String(s).replaceAll('\\', '\\\\').replaceAll("'", "\\'");

const locatorMethod = (name, def) => {
  let ret;
  if (def.role) {
    ret = def.name
      ? `return this.page.getByRole('${def.role}', { name: '${sq(def.name)}' });`
      : `return this.page.getByRole('${def.role}');`;
  } else if (def.testId) {
    ret = `return this.page.getByTestId('${sq(def.testId)}');`;
  } else if (def.css) {
    const note = def.note ? `    // ${def.note}\n` : '';
    return `  ${name}(): Locator {\n${note}    return this.page.locator('${sq(def.css)}');\n  }`;
  } else {
    throw new Error(`locator '${name}' has no supported kind (role/testId/css)`);
  }
  return `  ${name}(): Locator {\n    ${ret}\n  }`;
};

const actionMethod = (action) => {
  const params = (action.params ?? []).join(', ');
  return (
    `  async ${action.name}(${params}): Promise<void> {\n` +
    `    // step: ${action.step}\n` +
    `    ${action.body}\n` +
    `  }`
  );
};

const genPage = (page) => {
  const locators = Object.entries(page.locators).map(([n, d]) => locatorMethod(n, d));
  const actions = (page.actions ?? []).map(actionMethod);
  const members = [...locators, ...actions].join('\n\n');
  return (
    banner() +
    `import type { Locator } from '@playwright/test';\n` +
    `import { BasePage } from '../../../../shared/BasePage.js';\n\n` +
    `export class ${page.name} extends BasePage {\n` +
    `  readonly path = '${sq(page.path)}';\n\n` +
    `${members}\n` +
    `}\n`
  );
};

const genFixtures = (pages) => {
  const imports = pages.map((p) => `import { ${p.name} } from './pages/${p.name}.js';`).join('\n');
  const typeFields = pages.map((p) => `  ${fixtureName(p.name)}: ${p.name};`).join('\n');
  const entries = pages
    .map(
      (p) =>
        `  ${fixtureName(p.name)}: async ({ page }, use) => {\n` +
        `    await use(new ${p.name}(page));\n` +
        `  },`,
    )
    .join('\n');
  return (
    banner() +
    `import { test as base, expect } from '@playwright/test';\n` +
    `${imports}\n\n` +
    `type Fixtures = {\n${typeFields}\n};\n\n` +
    `export const test = base.extend<Fixtures>({\n${entries}\n});\n\n` +
    `export { expect };\n`
  );
};

const genSeed = (manifest) => {
  const note = manifest.seed?.note ?? 'Setup only — excluded from normal runs via testIgnore.';
  return (
    banner() +
    `// ${note}\n` +
    `import { test, expect } from '../fixtures.js';\n\n` +
    `test('seed: anchor site is reachable before the suite', async ({ page }) => {\n` +
    `  const response = await page.goto('/');\n` +
    `  expect(response?.ok()).toBeTruthy();\n` +
    `});\n`
  );
};

const emitRegex = (urlRegex) => `/${String(urlRegex).replaceAll('/', '\\/')}/`;

const genJourney = (journey, pageByName) => {
  const page = pageByName.get(journey.page);
  if (!page) throw new Error(`journey '${journey.id}' references unknown page '${journey.page}'`);
  const fx = fixtureName(page.name);
  const actionByName = new Map((page.actions ?? []).map((a) => [a.name, a]));
  const usesPage = (journey.assert ?? []).some((a) => a.kind === 'url');

  const stepLines = (journey.steps ?? []).map((s) => {
    const action = actionByName.get(s.action);
    if (!action) throw new Error(`journey '${journey.id}' step calls unknown action '${s.action}'`);
    const args = (s.args ?? []).map((v) => JSON.stringify(v)).join(', ');
    return `  // step ${s.step}: ${action.step}\n  await ${fx}.${s.action}(${args});`;
  });

  const assertLines = (journey.assert ?? []).map((a) => {
    if (a.kind === 'url') return `  await expect(page).toHaveURL(${emitRegex(a.urlRegex)});`;
    if (a.kind === 'visible') return `  await expect(${fx}.${a.locator}()).toBeVisible();`;
    if (a.kind === 'count' && a.op === '>=')
      return `  await expect.poll(() => ${fx}.${a.locator}().count()).toBeGreaterThanOrEqual(${a.value});`;
    throw new Error(`journey '${journey.id}' has unsupported assert ${JSON.stringify(a)}`);
  });

  const args = usesPage ? `{ page, ${fx} }` : `{ ${fx} }`;
  const body = [
    `  await ${fx}.goto();`,
    ...stepLines,
    `  // evidence: ${journey.evidence}`,
    ...assertLines,
  ].join('\n');

  return (
    banner() +
    `// specSource: manifest journey "${journey.id}"\n` +
    `// requirement: ${journey.requirement}\n` +
    `// risk: ${journey.risk}\n` +
    `// owner: ${journey.owner} · layer: ${journey.layer} · ciTier: ${journey.ciTier}\n` +
    `import { test, expect } from '../../fixtures.js';\n\n` +
    `test('${sq(journey.requirement)}', async (${args}) => {\n${body}\n});\n`
  );
};

// journey id "live-tv.guide-lists-channels" -> tests/live-tv/guide-lists-channels.spec.ts
const journeyPath = (id) => {
  const dot = id.indexOf('.');
  const dir = dot === -1 ? '' : id.slice(0, dot);
  const name = dot === -1 ? id : id.slice(dot + 1);
  return join('tests', dir, `${name}.spec.ts`);
};

const build = async () => {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  const pageByName = new Map(manifest.pages.map((p) => [p.name, p]));
  const files = new Map();

  for (const page of manifest.pages) files.set(join('pages', `${page.name}.ts`), genPage(page));
  files.set('fixtures.ts', genFixtures(manifest.pages));
  files.set('tests/seed.spec.ts', genSeed(manifest));
  for (const journey of manifest.journeys) {
    files.set(journeyPath(journey.id), genJourney(journey, pageByName));
  }

  // Format every file with the repo's Prettier config so output always matches format:check.
  const formatted = new Map();
  for (const [rel, raw] of files) {
    const abs = join(OUT_DIR, rel);
    const options = (await prettier.resolveConfig(abs)) ?? {};
    formatted.set(rel, await prettier.format(raw, { ...options, filepath: abs }));
  }
  return formatted;
};

const listFiles = (dir, acc = [], root = dir) => {
  if (!existsSync(dir)) return acc;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) listFiles(abs, acc, root);
    else acc.push(relative(root, abs));
  }
  return acc;
};

const OUT_DIR = resolve(
  REPO_ROOT,
  JSON.parse(readFileSync(MANIFEST_PATH, 'utf8')).playwrightFramework.outDir,
);

const files = await build();

if (check) {
  const drift = [];
  for (const [rel, content] of files) {
    const abs = join(OUT_DIR, rel);
    if (!existsSync(abs)) drift.push(`missing: ${rel}`);
    else if (readFileSync(abs, 'utf8') !== content) drift.push(`out of date: ${rel}`);
  }
  for (const rel of listFiles(OUT_DIR)) {
    if (!files.has(rel.split('\\').join('/'))) drift.push(`stale (not in manifest): ${rel}`);
  }
  if (drift.length) {
    process.stderr.write(
      `gen-framework --check FAILED — output does not match the manifest:\n` +
        drift.map((d) => `  ${d}`).join('\n') +
        `\nRun \`npm run gen:framework\` and commit the result.\n`,
    );
    process.exit(1);
  }
  process.stdout.write(
    `gen-framework OK — ${files.size} generated file(s) match ${MANIFEST_REL}\n`,
  );
} else {
  // Rewrite wholesale so removed journeys don't leave stale specs behind.
  for (const sub of ['pages', 'tests'])
    rmSync(join(OUT_DIR, sub), { recursive: true, force: true });
  rmSync(join(OUT_DIR, 'fixtures.ts'), { force: true });
  for (const [rel, content] of files) {
    const abs = join(OUT_DIR, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  process.stdout.write(
    `gen-framework wrote ${files.size} file(s) -> ${relative(REPO_ROOT, OUT_DIR)}\n` +
      [...files.keys()].map((rel) => `  ${rel}\n`).join('') +
      '  0 files hand-edited.\n',
  );
}
